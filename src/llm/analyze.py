import os
from pathlib import Path
import json

import pandas as pd
import matplotlib.pyplot as plt
import requests


PREDICTIONS_PATH = Path("artifacts/predictions/predictions.csv")
OUTPUT_DIR = Path("artifacts/analysis")
CHART_DIR = Path("artifacts/charts")

OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434/api/generate")
MODEL_NAME = "llama3.2:3b"


def load_predictions():
    return pd.read_csv(PREDICTIONS_PATH)


def compute_summary(df: pd.DataFrame):
    summary = {
        "average_salary": float(df["predicted_salary_usd"].mean()),
        "max_salary": float(df["predicted_salary_usd"].max()),
        "min_salary": float(df["predicted_salary_usd"].min()),
    }

    salary_by_experience = (
        df.groupby("experience_level")["predicted_salary_usd"]
        .mean()
        .to_dict()
    )

    summary["salary_by_experience"] = salary_by_experience

    return summary


def generate_chart(df: pd.DataFrame):
    CHART_DIR.mkdir(parents=True, exist_ok=True)

    chart_path = CHART_DIR / "salary_by_experience.png"

    avg_salary = (
        df.groupby("experience_level")["predicted_salary_usd"]
        .mean()
        .sort_index()
    )

    avg_salary.plot(kind="bar")
    plt.title("Average Salary by Experience Level")
    plt.xlabel("Experience Level")
    plt.ylabel("Salary (USD)")
    plt.tight_layout()

    plt.savefig(chart_path)
    plt.close()

    return chart_path


def call_ollama(prompt: str) -> str:
    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL_NAME,
            "prompt": prompt,
            "stream": False,
        },
        timeout=60,
    )

    response.raise_for_status()
    return response.json()["response"]


def build_prompt(summary: dict):
    return f"""
You are a professional data analyst.

You are analyzing salary predictions generated by a machine learning model.
Do not invent trends that are not directly supported by the data.
Do not mention time trends unless year-based comparisons are explicitly provided.

Here is the summary data:

Average salary: {summary['average_salary']:.2f}
Maximum salary: {summary['max_salary']:.2f}
Minimum salary: {summary['min_salary']:.2f}

Average predicted salary by experience level:
{summary['salary_by_experience']}

Write a short analytical narrative that includes:
1. the biggest salary differences across experience levels,
2. the most notable insight from the predictions,
3. one practical takeaway for someone exploring data careers.

Keep it concise, specific, and evidence-based.
"""

def main():
    print("Loading predictions...")
    df = load_predictions()

    print("Computing summary...")
    summary = compute_summary(df)

    print("Generating chart...")
    chart_path = generate_chart(df)

    print("Calling Ollama...")
    prompt = build_prompt(summary)
    analysis_text = call_ollama(prompt)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    summary_path = OUTPUT_DIR / "summary.json"
    analysis_path = OUTPUT_DIR / "analysis.txt"

    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)

    with open(analysis_path, "w", encoding="utf-8") as f:
        f.write(analysis_text)

    print("Analysis complete!")
    print(f"Chart saved at: {chart_path}")
    print(f"Analysis saved at: {analysis_path}")


if __name__ == "__main__":
    main()